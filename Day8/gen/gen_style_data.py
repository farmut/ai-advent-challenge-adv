def rows(items, start):
    return [{"id": f"ST-{start + i:03d}", "task": "style", "topic_id": t, "question": q, "answer": a}
            for i, (t, q, a) in enumerate(items)]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    train, valid = rows(TRAIN, 1), rows(VALID, len(TRAIN) + 1)
    for name, data in (("train", train), ("valid", valid)):
        with open(OUT / f"{name}.jsonl", "w", encoding="utf-8") as f:
            for r in data:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    topics = {"train": sorted({r["topic_id"] for r in train}), "valid": sorted({r["topic_id"] for r in valid})}
    topics["all"] = sorted(set(topics["train"]) | set(topics["valid"]))
    (OUT / "topics_used.json").write_text(json.dumps(topics, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"train {len(train)}, valid {len(valid)}, topics {len(topics['all'])}")


if __name__ == "__main__":
    main()
