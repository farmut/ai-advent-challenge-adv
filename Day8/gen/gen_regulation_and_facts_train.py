def end(opener: str) -> str:
    """Direct question after a colon gets '?', an indirect one after a comma gets '.'."""
    return "?" if opener.rstrip().endswith(":") else "."


def lcfirst(s: str) -> str:
    return s[0].lower() + s[1:]


def ucfirst(s: str) -> str:
    return s[0].upper() + s[1:]


def rows_for(i: int, fid: str, keys: list, s: dict) -> tuple[list, dict]:
    ask = s["ask"]
    co = f" {IN_CO}" if i % 2 == 0 else ""
    qa = {
        "T1": (f"{ucfirst(ask)}{co}?", s["ans"]),
        "T2": (f"{T2_OPEN[i % len(T2_OPEN)]}{ask}?", f"По регламенту {lcfirst(s['ans'])}"),
        "T3": (f"{s['sit']}{T3_JOIN[i % len(T3_JOIN)]}{ask}{end(T3_JOIN[i % len(T3_JOIN)])}", f"Учтите: {lcfirst(s['ans'])}"),
        "T4": (f"{T4_OPEN[i % len(T4_OPEN)]}{s['stem']} …»", f"{s['stem']} {s['val']}."),
        "T5": (f"Правда ли, что{' ' + IN_CO if i % 3 == 0 else ''} {s['wrong']}?", s["fix"]),
        "V1": (f"{V1_OPEN[i % len(V1_OPEN)]}{ask}{end(V1_OPEN[i % len(V1_OPEN)])}", f"Согласно регламенту, {lcfirst(s['ans'])}"),
    }
    out = []
    for t, (q, a) in qa.items():
        out.append({
            "id": f"FT-{fid}-{t}", "task": "facts", "fact_id": fid, "strata": "valid" if t == "V1" else "train",
            "template_id": t, "lang": "ru", "question": q, "answer": a, "answer_keys": keys,
        })
    return [r for r in out if r["strata"] == "train"], next(r for r in out if r["strata"] == "valid")


